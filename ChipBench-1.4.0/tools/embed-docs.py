#!/usr/bin/env python3
"""Embed docs/*.md into app/js/docs-data.js so the manual works offline inside ChipBench.  Run from anywhere: python tools/embed-docs.py"""
import json, pathlib, sys
root = pathlib.Path(__file__).resolve().parent.parent
docs = {}
for n in ['MANUAL', 'SHORTCUTS', 'DEVELOPMENT', 'IP-ATLAS', 'CHANGELOG', 'CREDITS']:
    p = root / 'docs' / (n + '.md'); docs[n] = p.read_text(encoding='utf-8') if p.is_file() else ''
    if not docs[n]: print('warning: docs/%s.md missing or empty' % n, file=sys.stderr)
# the in-app manual carries the product definition, Ethernet tools and skills as appendices
for i, n in enumerate(['PRODUCT', 'ETHERNET', 'SKILLS']):
    p = root / 'docs' / (n + '.md')
    if p.is_file(): docs['MANUAL'] += '\n\n---\n\n' + p.read_text(encoding='utf-8').replace('# ', '# 附录 %s · ' % 'ABC'[i], 1)
out = root / 'app' / 'js' / 'docs-data.js'
out.write_text('/* generated by tools/embed-docs.py — edit docs/*.md instead */\n(function(G){var SL=G.ChipBench=G.ChipBench||{};SL.s31=SL.s31||{};SL.s31.docs=' + json.dumps(docs, ensure_ascii=False).replace('</', '<\\/') + ';})(window);\n', encoding='utf-8')
print('wrote', out.relative_to(root), '(%d KB)' % (out.stat().st_size // 1024))
