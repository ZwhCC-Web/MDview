#!/usr/bin/env python3
"""ChipBench 前端模块清单工具。
  python tools/check-modules.py            校验：文件存在 / 依赖顺序 / index.html 与清单一致 / 未登记文件 / 依赖环
  python tools/check-modules.py --write    按 app/modules.json 重写 index.html 的脚本列表、js/modules-registry.js、docs/MODULES.md
  python tools/check-modules.py --report   额外列出“运行期晚绑定”引用（模块 A 使用了在更晚模块里才定义的 SL.xxx）
清单 app/modules.json 是加载顺序与依赖的唯一事实来源。"""
import json, pathlib, re, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent; APP = ROOT / 'app'; JS = APP / 'js'
M = json.loads((APP / 'modules.json').read_text('utf-8'))['modules']; ids = [m['id'] for m in M]; by = {m['id']: m for m in M}
BEGIN, END = '<!-- modules:begin (generated by tools/check-modules.py --write) -->', '<!-- modules:end -->'
errs, warns = [], []
eager = lambda: [m for m in M if not m.get('lazy')]
def check():
    if len(set(ids)) != len(ids): errs.append('清单里有重复的 id')
    files = {p.name for p in JS.glob('*.js')}
    for m in M:
        if not (JS / m['file']).exists(): errs.append(f"{m['id']}: 文件不存在 {m['file']}")
        for d in m['deps']:
            if d not in by: errs.append(f"{m['id']}: 依赖未登记的模块 {d}")
    for f in sorted(files - {m['file'] for m in M}): errs.append(f'app/js/{f} 没有登记到 modules.json')
    pos = {m['id']: i for i, m in enumerate(eager())}
    for m in eager():
        for d in m['deps']:
            if d in by and by[d].get('lazy'): errs.append(f"{m['id']}: 启动模块不能依赖懒加载模块 {d}")
            elif d in pos and pos[d] > pos[m['id']]: errs.append(f"{m['id']}: 依赖 {d} 排在它后面（加载顺序错误）")
    st = {}
    def dfs(n, path):
        if st.get(n) == 1: errs.append('依赖环：' + ' → '.join(path + [n])); return
        if st.get(n) == 2: return
        st[n] = 1
        for d in by[n]['deps']:
            if d in by: dfs(d, path + [n])
        st[n] = 2
    for n in ids: dfs(n, [])
    html = (APP / 'index.html').read_text('utf-8'); got = re.findall(r'src="js/([^"]+)"', html)
    if got != [m['file'] for m in eager()]: errs.append('index.html 的脚本列表与 modules.json 不一致（运行 python tools/check-modules.py --write）')
    lazy_files = {m['file'] for m in M if m.get('lazy')}
    for g in got:
        if g in lazy_files: errs.append(f'懒加载模块 {g} 不应写进 index.html')
def report():
    src = {m['id']: (JS / m['file']).read_text('utf-8') for m in M if (JS / m['file']).exists()}; defs = {}
    for i, s in src.items():
        for x in re.finditer(r'\b(?:SL|S)\.([A-Za-z_]\w*)\s*=[^=]', s): defs.setdefault(x.group(1), set()).add(i)
    order = {m['id']: k for k, m in enumerate(M)}; print('运行期晚绑定引用（调用发生在启动之后，安全；但属于隐式耦合）：')
    for i, s in src.items():
        own = {k for k, v in defs.items() if i in v}; late = {}
        for u in set(re.findall(r'\bSL\.([A-Za-z_]\w*)', s)) - own:
            for g in defs.get(u, ()):
                if g != i and order[g] > order[i]: late.setdefault(g, set()).add(u)
        if late: print(f'  {i} → ' + '；'.join(f"{g}: {', '.join(sorted(v)[:4])}" for g, v in late.items()))
def write():
    html = (APP / 'index.html').read_text('utf-8'); tags = '\n'.join(f'<script src="js/{m["file"]}"></script>' for m in eager()); block = f'{BEGIN}\n{tags}\n{END}'
    if BEGIN in html: html = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda _: block, html, flags=re.S)
    else:
        i = html.index('<script src="js/logic.js">'); j = html.index('</body>'); html = html[:i] + block + '\n' + html[j:]
    (APP / 'index.html').write_text(html, 'utf-8')
    reg = 'ChipBench.rt.modules.registerAll(' + json.dumps([{k: m[k] for k in ('id', 'file', 'deps')} | ({'lazy': True} if m.get('lazy') else {}) for m in M], ensure_ascii=False, separators=(',', ':')) + ');'
    (JS / 'modules-registry.js').write_text('/* generated by tools/check-modules.py --write — do not edit */\n' + reg + '\n', 'utf-8')
    L = {'kernel': '内核', 'core': '应用壳', 'workspace': '工作空间', 'viewer': '文档中心', 'engineering': '工程中心', 'tools': '工程工具', 'automation': '自动化中心', 'ux': '体验增强'}
    md = ['# 前端模块图（自动生成）', '', '由 `tools/check-modules.py --write` 从 `app/modules.json` 生成；加载顺序即表格顺序。虚线 = 懒加载。', '', '| # | 模块 | 层 | 依赖 | 加载 | 说明 |', '|---|---|---|---|---|---|']
    for k, m in enumerate(M, 1): md.append(f"| {k} | `{m['file']}` | {L.get(m['layer'], m['layer'])} | {', '.join(m['deps']) or '—'} | {'按需' if m.get('lazy') else '启动'} | {m.get('note', '')} |")
    md += ['', '```mermaid', 'graph LR']
    for m in M:
        for d in m['deps']: md.append(f"  {d.replace('-', '_')} {'-.->' if m.get('lazy') else '-->'} {m['id'].replace('-', '_')}")
    md.append('```'); (ROOT / 'docs' / 'MODULES.md').write_text('\n'.join(md) + '\n', 'utf-8')
if __name__ == '__main__':
    if '--write' in sys.argv: write()
    check()
    if '--report' in sys.argv: report()
    if errs: print('\n'.join('FAIL: ' + e for e in errs)); sys.exit(1)
    print(f'modules OK ({len(M)} modules, {len(eager())} eager, {len(M) - len(eager())} lazy)')
